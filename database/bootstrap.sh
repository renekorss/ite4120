#!/bin/sh
set -eu
export MIGRATION_PASSWORD="$(cat /run/secrets/postgres_password)"
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'SQL'
CREATE ROLE migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
CREATE ROLE reminder_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE reminder_retention NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE reminder_auditor NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;
ALTER SCHEMA public OWNER TO migrator;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO migrator;
\getenv migration_password MIGRATION_PASSWORD
ALTER ROLE migrator PASSWORD :'migration_password';
SQL
unset MIGRATION_PASSWORD
